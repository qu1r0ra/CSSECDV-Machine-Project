    /** Refreshes the read-only view using the audit provider's parameterized text filter. */
    public void searchLogs(String text) {
        searchField.setText(text == null ? "" : text);
        tableModel.setRowCount(0);
        try {
            ArrayList<Logs> logs = sqlite.getLogs(access, searchField.getText(), "");
            for (Logs log : logs) {
                tableModel.addRow(new Object[] {log.getEvent(), log.getUsername(), log.getDesc(), log.getTimestamp()});
            }
            statusLabel.setText(logs.isEmpty() ? "No audit records match this search."
                    : logs.size() + " audit record(s) shown.");
        } catch (RuntimeException ex) {
            tableModel.setRowCount(0);
            statusLabel.setText("Audit records are unavailable right now.");
        }
    }

    /** Clears only the search field and restores the read-only all-records view. */
    public void showAllLogs() {
        searchField.setText("");
        searchLogs("");
    }

